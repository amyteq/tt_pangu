def _parse_deadline(raw: str | None):
    if not raw:
        return None
    try:
        return _dt.date.fromisoformat(raw)
    except ValueError as exc:
        raise ValueError(f"--deadline must be yyyy-mm-dd, got {raw!r}") from exc


def cmd_init(args: argparse.Namespace) -> int:
    slug = args.competition
    try:
        _db = _load_db()
        comp = _db.get_competition_by_slug(slug)
        deadline = _parse_deadline(getattr(args, "deadline", None))
    except KeyError:
        return _emit(
            False,
            {
                "error": f"competition '{slug}' not registered; run `kca competition register` first",
                "side_effect": SideEffect.LOCAL_WRITE.value,
            },
            EXIT_RUNTIME,
        )
    except Exception as exc:
        return _emit(
            False,
            {"error": str(exc), "side_effect": SideEffect.LOCAL_WRITE.value},
            EXIT_RUNTIME,
        )

    try:
        goal_id = _db.create_goal(
            comp["id"],
            target_lb_score=args.target_lb_score,
            target_lb_rank=getattr(args, "target_lb_rank", None),
            target_rank_kind=getattr(args, "target_rank_kind", None),
            deadline=deadline,
            exit_strategy=args.exit_strategy,
            max_total_pushes=args.max_total_pushes,
            stuck_threshold=args.stuck_threshold,
        )
    except _db.ActiveGoalExists:
        return _emit(
            False,
            {
                "error": "ACTIVE_GOAL_EXISTS",
                "competition": slug,
                "message": ("an active goal already exists for this competition; `kca goal update --close` it first"),
                "side_effect": SideEffect.LOCAL_WRITE.value,
            },
            EXIT_RUNTIME,
        )
    except Exception as exc:
        return _emit(
            False,
            {"error": str(exc), "side_effect": SideEffect.LOCAL_WRITE.value},
            EXIT_RUNTIME,
        )

    row = _db.get_active_goal(comp["id"]) or {}
    md_path = _write_goal_md(slug, row)
    return _emit(
        True,
        {
            "goal_id": goal_id,
            "competition": slug,
            "goal": goal_md_fields(slug, row),
            "goal_md": str(md_path),
            "side_effect": SideEffect.LOCAL_WRITE.value,
        },
    )


def cmd_show(args: argparse.Namespace) -> int:
    slug = args.competition
    try:
        _db = _load_db()
        comp = _db.get_competition_by_slug(slug)
        row = _db.get_active_goal(comp["id"])
    except KeyError:
        return _emit(
            False,
            {
                "error": f"competition '{slug}' not registered",
                "side_effect": SideEffect.READ_ONLY.value,
            },
            EXIT_RUNTIME,
        )
    except Exception as exc:
        return _emit(
            False,
            {"error": str(exc), "side_effect": SideEffect.READ_ONLY.value},
            EXIT_RUNTIME,
        )

    if row is None:
        return _emit(
            False,
            {
                "error": "NO_ACTIVE_GOAL",
                "competition": slug,
                "side_effect": SideEffect.READ_ONLY.value,
            },
            EXIT_RUNTIME,
        )

    delta = goal_remaining_delta(_db, comp["id"], row)
    return _emit(
        True,
        {
            "competition": slug,
            "goal_id": str(row.get("id", "")),
            "goal": goal_md_fields(slug, row),
            "goal_remaining_delta": delta,
            "closed_at": _iso(row.get("closed_at")),
            "closed_reason": row.get("closed_reason"),
            "side_effect": SideEffect.READ_ONLY.value,
        },
    )


def cmd_update(args: argparse.Namespace) -> int:
    slug = args.competition
    try:
        _db = _load_db()
        comp = _db.get_competition_by_slug(slug)
        row = _db.get_active_goal(comp["id"])
    except KeyError:
        return _emit(
            False,
            {
                "error": f"competition '{slug}' not registered",
                "side_effect": SideEffect.LOCAL_WRITE.value,
            },
            EXIT_RUNTIME,
        )
    except Exception as exc:
        return _emit(
            False,
            {"error": str(exc), "side_effect": SideEffect.LOCAL_WRITE.value},
            EXIT_RUNTIME,
        )

    if row is None:
        return _emit(
            False,
            {
                "error": "NO_ACTIVE_GOAL",
                "competition": slug,
                "side_effect": SideEffect.LOCAL_WRITE.value,
            },
            EXIT_RUNTIME,
        )

    goal_id = str(row["id"])
    try:
        deadline = _parse_deadline(getattr(args, "deadline", None))
        if getattr(args, "close", False):
            _db.close_goal(goal_id, status=args.status, reason=args.reason)
        else:
            _db.update_goal(
                goal_id,
                target_lb_score=getattr(args, "target_lb_score", None),
                target_lb_rank=getattr(args, "target_lb_rank", None),
                target_rank_kind=getattr(args, "target_rank_kind", None),
                deadline=deadline,
                exit_strategy=getattr(args, "exit_strategy", None),
                max_total_pushes=getattr(args, "max_total_pushes", None),
                stuck_threshold=getattr(args, "stuck_threshold", None),
            )
    except Exception as exc:
        return _emit(
            False,
            {"error": str(exc), "side_effect": SideEffect.LOCAL_WRITE.value},
            EXIT_RUNTIME,
        )

    # Re-read: a close moves the row out of 'active', so fetch by id.
    updated = _read_goal_by_id(_db, goal_id) or row
    md_path = _write_goal_md(slug, updated)
    return _emit(
        True,
        {
            "goal_id": goal_id,
            "competition": slug,
            "closed": bool(getattr(args, "close", False)),
            "goal": goal_md_fields(slug, updated),
            "closed_at": _iso(updated.get("closed_at")),
            "closed_reason": updated.get("closed_reason"),
            "goal_md": str(md_path),
            "side_effect": SideEffect.LOCAL_WRITE.value,
        },
    )


def _read_goal_by_id(_db, goal_id: str) -> dict | None:
    conn = _db.get_conn()
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT * FROM goals WHERE id = %s::uuid", (goal_id,))
            row = cur.fetchone()
    finally:
        conn.close()
    return dict(row) if row else None


def add_parsers(sub: argparse._SubParsersAction) -> None:
    goal = sub.add_parser("goal", help="Declare / inspect / update a per-competition goal (M14)")
    goal_sub = goal.add_subparsers(dest="goal_cmd", required=True)

    p_init = goal_sub.add_parser("init", help="Create the goals row + write goal.md (LOCAL_WRITE)")
    p_init.add_argument("--competition", required=True, help="competition slug")
    p_init.add_argument(
        "--target-lb-score",
        dest="target_lb_score",
        type=float,
        default=None,
        help="primary target (absolute public LB score)",
    )
    p_init.add_argument(
        "--target-lb-rank",
        dest="target_lb_rank",
        type=int,
        default=None,
        help="secondary target (rank; best-effort)",
    )
    p_init.add_argument(
        "--target-rank-kind",
        dest="target_rank_kind",
        choices=("percentile", "absolute"),
        default=None,
    )
    p_init.add_argument("--deadline", default=None, help="yyyy-mm-dd (optional)")
    p_init.add_argument(
        "--exit-strategy",
        dest="exit_strategy",
        choices=("first_reached", "all_required", "score_only", "rank_only"),
        default="first_reached",
    )
    p_init.add_argument("--max-total-pushes", dest="max_total_pushes", type=int, default=20)
    p_init.add_argument("--stuck-threshold", dest="stuck_threshold", type=int, default=3)
    p_init.add_argument("--json", action="store_true")
    p_init.set_defaults(func=cmd_init)

    p_show = goal_sub.add_parser("show", help="Show the active goal + goal_remaining_delta (READ_ONLY)")
    p_show.add_argument("--competition", required=True)
    p_show.add_argument("--json", action="store_true")
    p_show.set_defaults(func=cmd_show)

    p_update = goal_sub.add_parser("update", help="Update fields or close the active goal (LOCAL_WRITE)")
    p_update.add_argument("--competition", required=True)
    p_update.add_argument("--target-lb-score", dest="target_lb_score", type=float, default=None)
    p_update.add_argument("--target-lb-rank", dest="target_lb_rank", type=int, default=None)
    p_update.add_argument(
        "--target-rank-kind",
        dest="target_rank_kind",
        choices=("percentile", "absolute"),
        default=None,
    )
    p_update.add_argument("--deadline", default=None, help="yyyy-mm-dd")
    p_update.add_argument(
        "--exit-strategy",
        dest="exit_strategy",
        choices=("first_reached", "all_required", "score_only", "rank_only"),
        default=None,
    )
    p_update.add_argument("--max-total-pushes", dest="max_total_pushes", type=int, default=None)
    p_update.add_argument("--stuck-threshold", dest="stuck_threshold", type=int, default=None)
    p_update.add_argument(
        "--close",
        action="store_true",
        help="Close the goal (set status + closed_at + closed_reason)",
    )
    p_update.add_argument(
        "--status",
        choices=("reached", "closed", "abandoned"),
        default="closed",
        help="Status to set on --close (default: closed)",
    )
    p_update.add_argument("--reason", default=None, help="closed_reason on --close")
    p_update.add_argument("--json", action="store_true")
    p_update.set_defaults(func=cmd_update)
