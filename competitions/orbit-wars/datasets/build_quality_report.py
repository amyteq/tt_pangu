"""Aggregate dataset-quality metrics into a markdown report.

  python build_quality_report.py --in-root <artifacts-dir> --out <report.md>

Reads episode_index_summary.json + episodes.jsonl + step_table.csv + candidates.jsonl
(whichever exist) and reports the metrics required by OW-P1-DATASET-001.
"""

from __future__ import annotations

import argparse
import csv
import json
import os


def _load_jsonl(p):
    if not os.path.exists(p):
        return []
    with open(p) as f:
        return [json.loads(line) for line in f if line.strip()]


def build(in_root, out_path):
    summ = {}
    sp = os.path.join(in_root, "episode_index_summary.json")
    if os.path.exists(sp):
        summ = json.load(open(sp))
    cands = _load_jsonl(os.path.join(in_root, "candidates.jsonl"))
    steps = 0
    stp = os.path.join(in_root, "step_table.csv")
    if os.path.exists(stp):
        with open(stp) as f:
            steps = sum(1 for _ in csv.reader(f)) - 1
    n = len(cands)
    valid = sum(1 for c in cands if c.get("oracle_valid"))
    unknown = sum(1 for c in cands if c.get("oracle_first_hit_type") in (None, "unknown", "none"))
    sun = sum(1 for c in cands if c.get("oracle_first_hit_type") == "sun")
    near = sum(1 for c in cands if (c.get("candidate_features_json") or {}).get("path_near_sun"))
    pos = sum(1 for c in cands if c.get("teacher_selected"))
    decoded = sum(1 for c in cands if c.get("oracle_first_hit_id", -1) not in (None, -1))

    def pct(a, b):
        return f"{100.0 * a / b:.1f}%" if b else "n/a"

    lines = [
        "# Orbit Wars dataset quality report",
        "",
        f"> Generated by `datasets/build_quality_report.py` from `{in_root}`.",
        "",
        "## Corpus",
        f"- replays seen: {summ.get('replays_seen', 'n/a')}",
        f"- indexed: {summ.get('indexed', 'n/a')}",
        f"- malformed replays: {summ.get('malformed', 'n/a')}",
        f"- total steps: {summ.get('total_steps', 'n/a')}",
        f"- 2p / 4p split: {summ.get('p2', 'n/a')} / {summ.get('p4', 'n/a')}",
        f"- top-player episodes: {summ.get('top_player_episodes', 'n/a')}",
        f"- step-table rows: {steps}",
        "",
        "## Candidates",
        f"- candidate rows: {n}",
        f"- action/first-hit decode rate: {pct(decoded, n)}",
        f"- first-hit unknown/none rate: {pct(unknown, n)}",
        f"- oracle-valid (target is first hit) rate: {pct(valid, n)}",
        f"- positive label (teacher_selected) rate: {pct(pos, n)}",
        f"- strict sun-collision labels: {sun}",
        f"- near-sun labels: {near}",
        "",
        "## Split policy + leakage",
        "- **Split by episode_id** (never by step) into train/valid/test ~ 80/10/10 so no step",
        "  from one game leaks across splits. Stratify by player_count (2p/4p) + top_player_flag.",
        "- Leakage checks: assert disjoint episode_id sets across splits; assert future_value_delta",
        "  (h20/h50) reads only steps from the SAME episode and t' > t.",
        "",
        "## Runtime",
        "- stdlib JSONL/CSV (no parquet dep). Fixture-smoke throughput is logged by each builder;",
        "  full 20G corpus runs on snorlax (see `datasets/README.md`).",
        "",
        "## Notes / blockers",
        "- Candidate labels use the deterministic **FlightOracle** (`core/oracle.py`) for first-hit/",
        "  safety + `core.state` features — not duplicate path logic (avoids the BC direct-policy mistake).",
        "- Comet expiry/path not modelled (`expires_in_if_comet`=None) — see battlefield-state schema doc.",
    ]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"quality report -> {out_path} (candidates={n}, steps={steps})")


def main():
    ap = argparse.ArgumentParser(description="Aggregate Orbit Wars dataset quality metrics.")
    ap.add_argument("--in-root", required=True, help="dataset artifacts dir")
    ap.add_argument("--out", required=True, help="output markdown report path")
    args = ap.parse_args()
    build(args.in_root, args.out)


if __name__ == "__main__":
    main()
