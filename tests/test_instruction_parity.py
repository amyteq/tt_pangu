# --- Sensitive mentions, pinned ----------------------------------------------
#
# Three rules on these surfaces are worth guarding by hand. Force-push is denied
# outright rather than gated, so a document that files it under "requires approval"
# tells a harness the operation has a path to yes. The ADR-0021 §2 / ADR-0022 §5
# autonomy grant is off until a competition meets A1-A7 and none does, so a document
# that states the screen as current permission grants what the tree withholds. And an
# approval rule in a mirrored skill has to say whom it binds, because a skill is read
# by both harnesses *after* the project doc and the answer differs by agent.
#
# Three earlier designs guarded them by deciding, per sentence, whether the English
# left a path to yes: first by weighing what sat next to a mention, then by adding
# contrast breaks and predicate attachment, then by inverting the enumerations so that
# passing required a listed token. Each looked sufficient when it shipped, and each
# lost the following round:
#
#     "Force-push is forbidden without explicit approval."     passed
#     "Force-push is not explicitly prohibited."               passed
#     "Force-push has no restrictions."                        passed
#     "Force-push is prohibited only when CI is red."          passed
#     "Force-push is barred provided the owner agrees."        passed
#     "Screened autonomy is not disabled."                     passed
#     "Screened autonomy is no longer inactive."               passed
#
# The third design inverted on itself, and that is the part worth keeping. Its denial
# check asked whether *any* denial token occurred in the clause, not whether the denial
# governed force-push — so the `no` in "no restrictions" discharged the requirement, and
# every negation word added to the list made the guard weaker rather than stronger. A
# fourth phrase list does not fix that. "Does this English sentence grant approvability?"
# is not a question a phrase list answers, and the evidence is now four rounds long.
#
# So this stops asking it, and asks a decidable neighbour instead:
#
#     has any sentence mentioning force-push, the autonomy screen, or an approval rule
#     in a mirrored skill changed since a reviewer last read it?
#
# Every such sentence on every scanned surface is pinned in `PINNED_MENTIONS`. The test
# fails when one is added, removed, altered or reordered, and prints the replacement
# table. It makes no claim about English at all — it claims only that these are the
# sentences that were reviewed, which is true by construction and stays true — and it
# routes every rewording of one of these rules back to review, which is what the three
# earlier designs were reaching for.
#
# What that gives up, plainly:
#
#   * It does not judge a mention the first time it is pinned. Nothing here says a newly
#     pinned sentence is correct; that rests on whoever reads the diff. This catches
#     drift away from reviewed text, not an original mistake in it.
#   * It fires on innocent rewording — a synonym, a clause reordered, a rule split in
#     two. That is the cost, not a defect. Rewrapping is not rewording and does not fire;
#     `test_reflowing_a_whole_surface_is_not_drift` hard-wraps three real surfaces and
#     expects silence. To update after a real edit: run this test, paste the literal it
#     prints over the matching rows of `PINNED_MENTIONS`, and quote the before/after in
#     the PR body — a reworded rule is a policy change and is reviewed as one.
#   * `MENTION_TOPICS`' triggers are the enumeration left, and an omission leaves a
#     sentence *unpinned* rather than wrongly admitted. That is a stated scope limit
#     rather than a defeated adjudication: a mention spelled in none of these ways
#     ("rewriting published history needs sign-off") is out of scope — not examined and
#     passed. They are written broad for exactly that reason: matching too much only pins
#     more sentences, which costs review time and nothing else. `POLICY_SURFACES` used to
#     be the second such enumeration and was wrong twice running, one file short each
#     time; it is now read off `AGENTS.md`'s own *Read first* list, so what a harness is
#     told to read and what this scans are the same list by construction.
#   * Code is scanned rather than skipped, so a *new* fenced example that mentions one of
#     the topics needs a pin row too. That is the price of tagging instead of ignoring,
#     and it buys the direction that matters: a rule demoted into a fence is reported.
#   * Which block a sentence sits in is read off markdown structure — fences, indentation,
#     all seven of CommonMark's raw-HTML start conditions, and one level of list-item
#     nesting. Markup that shares a line with the sentence lands in the pinned text,
#     because `_plain` strips markdown emphasis and ticks and never HTML, so that edit is
#     reported as altered text instead of as a new tag;
#     `test_the_mention_scanner_extracts_these_sentences` carries both halves.
#
#     #217 opened with three shapes where the under-tagging meant *missing* rather than
#     erring safe: the rule was demoted or hidden in the rendered document while its pin
#     stayed byte-identical and the diff stayed empty. Two are closed here and the third is
#     not closable by a block classifier. All of it was adjudicated against `markdown-it` in
#     CommonMark mode, which is the arbiter throughout:
#
#       1. Closed. Condition 7 was gated on a preceding blank line; CommonMark gates it on
#          not interrupting a *paragraph*, which is weaker, because once a block has ended
#          the next line may open one with no blank between. `_line_blocks` now tracks
#          whether a paragraph is open and passes that, which is what `_html_block`'s
#          `may_start` always claimed to be. So `<span style="display:none">` on the line
#          after a one-line comment is an `html_block` to CommonMark and `[html] ` here.
#       2. Closed for one level of nesting. A start condition is measured from the
#          enclosing list item's content column rather than from column 0, so `<!--` four
#          spaces into a `- ` item is the real start CommonMark reads it as. `_undent` does
#          the shifting and only for the start tests; the tag and the pinned text keep
#          reading the real line.
#       3. Not closed, and accepted as residual risk rather than left implicit. Inline HTML
#          is never inspected. That one is not a misclassification: when a tag does
#          interrupt a paragraph CommonMark agrees it is inline, and this agrees. But an
#          unclosed `display:none` span on a neighbouring line still hides the rule without
#          altering one byte of it, so there is nothing for a *block* classifier to report.
#          Closing it means reasoning about unclosed inline tags across a whole document,
#          which is a different guard and a far larger surface than this drift check.
#          Fixing 1 and 2 left it standing, exactly as #217 predicted.
#
#     What is still bounded rather than closed, measured and pinned by
#     `test_container_tracking_reaches_one_level_and_these_are_outside_it`: container
#     tracking follows the innermost list marker that sits within `^ {0,3}`, which covers
#     every list on every scanned surface, so a marker indented four or more — a second
#     level nested that deep — is measured from too far right and its start is missed. A
#     blockquote needs no bound: hiding a rule inside one puts `> ` on the rule's own line,
#     which is reported as altered text, and leaving the rule outside the quote does not
#     hide it at all.
#
#     An earlier draft of this comment claimed only line-sharing markup could leave a
#     sentence byte-identical, so container nesting could only under-tag. The round 9
#     review of #202 disproved it, #217 recorded it, and the claim now matches the code:
#     this reports a rule moved into a fence, into `<pre>`, into a comment that opens
#     anywhere CommonMark opens one within a tracked container, or behind a condition-7
#     start that does not interrupt a paragraph — and does not report shape 3 or a start
#     below a marker indented past column 3.
#
# The pinned text is the sentence with markdown emphasis and code ticks removed and its
# whitespace collapsed: those are rendering, so a bold/plain or hard-wrap/soft-wrap
# change is not drift. The trigger reads that same normalised form, not the source line,
# or a trigger spelled with a space would stop matching its own rule as soon as the line
# broke between those two words. Stripping `*` does mangle a glob
# (`.kca/permissions/*.yaml` pins as `.kca/permissions/.yaml`); the pin only ever compares
# itself to itself, so that costs readability and not correctness.
#
# Being code is not rendering, though. A rule moved into a fenced block, or wrapped whole
# in inline code, stops being a rule and becomes an illustration — and with the ticks
# stripped it would otherwise pin byte-identical to the prose it replaced, so the edit
# would pass unseen. The pin therefore carries the block its sentence was found in: code
# pins under `[code] `, prose under `[prose] `, and moving one into the other is reported
# as an addition and a removal. `_blocks` reads that off markdown structure, which is
# decidable, and never off what the sentence says.
#
# Every block is tagged, and that is the whole of why the tag means anything. Tagging only
# code left the prose tag as *absence of a prefix*, which document text can supply for
# itself: a prose sentence beginning with the literal characters `[code] ` pinned exactly
# as the same sentence inside a fence, so that one code-to-prose move stayed invisible.
# Tags of which none is a prefix of another make the map injective by construction: the
# block is decided before any of the sentence is read, and no text the sentence carries
# can change it. The cost is a tag on every row, which also makes the block explicit to
# read rather than implied by a missing prefix.
#
# Markdown code is not the only way to change what a sentence *is*. A raw HTML block is
# passed through untouched, so `<pre>` around a rule makes it preformatted code and
# `<!-- -->` around it takes it out of the rendered document altogether — neither is a
# wording change, and both pinned byte-identical to the prose rule they replaced until
# this was written. So raw HTML tags by what the reader is left with, which is the same
# question the fence split asks:
#
#   * `<pre>` is `[code] `, because that is what the page shows — the same tag a fence
#     gets, for the same reason.
#   * A block whose text still renders but whose markdown no longer runs — `<div>`,
#     `<table>`, and the rest of CommonMark's conditions 6 and 7, plus `<textarea>` — is
#     `[html] `. A bullet in there is the characters `- `, not a list item, and
#     `<div style="display:none">` is not visible at all; neither is prose.
#   * A block the reader never sees — an HTML comment, `<script>`, `<style>`, a
#     processing instruction, a declaration, CDATA — is `[hidden] `. It earns its own tag
#     because the sentence has left the document rather than changed style, and the diff
#     row is then the difference between "this rule became an example" and "this rule is
#     gone". Commenting a rule out is the worst of these edits and should read as such.
CODE_PIN = "[code] "
PROSE_PIN = "[prose] "
HTML_PIN = "[html] "
HIDDEN_PIN = "[hidden] "
# Total: `_line_blocks` returns one of these for every line it does not drop, and
