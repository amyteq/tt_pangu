"""kca goal: declare / inspect / update a per-competition goal (M14-T002).

A goal is declared per competition. The DB ``goals`` row (migration 0011,
M14-T001) is authoritative; ``experiments/<comp>/goal.md`` is a human-readable
mirror for git history (ADR-0020 §1). This module owns the CLI surface and the
``goal.md`` writer; all DB writes go through the T001 helpers in ``db.py``.

Subcommands:
  - ``kca goal init``   — create the goals row (refuses if one is active) + write goal.md
  - ``kca goal show``   — read the active goal + goal_remaining_delta
  - ``kca goal update`` — partial update / close; rewrites goal.md

``goal_remaining_delta`` (best current public LB vs target_lb_score) is a
read-only enrichment: positive means the loop is still below target for a
higher-is-better metric; NULL when no scored submission or no target exists
(ADR-0020 §1 — a NULL rank/score never blocks the loop).
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
from pathlib import Path

from _types import EXIT_OK, EXIT_RUNTIME, SideEffect

# Fields mirrored between the goals row and goal.md front-matter (ADR-0020 §1).
_GOAL_MD_FIELDS = (
    "competition",
    "target_lb_score",
    "target_lb_rank",
    "target_rank_kind",
    "deadline",
    "exit_strategy",
    "max_total_pushes",
    "stuck_threshold",
    "status",
)


def _emit(ok: bool, payload: dict, exit_code: int = EXIT_OK) -> int:
    print(json.dumps({"ok": ok, **payload}, ensure_ascii=False, default=str))
    return exit_code


def _load_db():
    import db as _db

    return _db


def _repo_root() -> Path:
    # tools/kca/goal.py -> repo root is two parents up from tools/kca/.
    return Path(__file__).resolve().parent.parent.parent


def _goal_md_path(slug: str) -> Path:
    return _repo_root() / "experiments" / slug / "goal.md"


# ---------------------------------------------------------------------------
# goal.md (front-matter mirror + human body)
# ---------------------------------------------------------------------------


def _iso(value) -> str | None:
    if value is None:
        return None
    if hasattr(value, "date"):  # datetime
        return value.date().isoformat()
    if hasattr(value, "isoformat"):  # date
        return value.isoformat()
    return str(value)


def _yaml_scalar(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return str(value)


def goal_md_fields(slug: str, row: dict) -> dict:
    """Project a goals row into the goal.md front-matter field dict."""
    return {
        "competition": slug,
        "target_lb_score": (float(row["target_lb_score"]) if row.get("target_lb_score") is not None else None),
        "target_lb_rank": (int(row["target_lb_rank"]) if row.get("target_lb_rank") is not None else None),
        "target_rank_kind": row.get("target_rank_kind"),
        "deadline": _iso(row.get("deadline")),
        "exit_strategy": row.get("exit_strategy"),
        "max_total_pushes": (int(row["max_total_pushes"]) if row.get("max_total_pushes") is not None else None),
        "stuck_threshold": (int(row["stuck_threshold"]) if row.get("stuck_threshold") is not None else None),
        "status": row.get("status"),
    }


def render_goal_md(slug: str, row: dict) -> str:
    """Render the full goal.md text (YAML front-matter + human body)."""
    fields = goal_md_fields(slug, row)
    lines = ["---"]
    for key in _GOAL_MD_FIELDS:
        lines.append(f"{key}: {_yaml_scalar(fields.get(key))}")
    lines.append("---")
    lines.append("")
    lines.append(f"# Goal — {slug}")
    lines.append("")
    lines.append(
        "_Auto-generated by `kca goal`. The DB `goals` row is authoritative; "
        "this file mirrors it for humans + git history (ADR-0020 §1)._"
    )
    lines.append("")
    score = fields.get("target_lb_score")
    rank = fields.get("target_lb_rank")
    rank_kind = fields.get("target_rank_kind")
    lines.append("## Target")
    lines.append("")
    if score is not None:
        lines.append(f"- **Public LB score (primary):** {score}")
    else:
        lines.append("- **Public LB score (primary):** _unset_")
    if rank is not None:
        lines.append(f"- **Rank (secondary):** {rank} ({rank_kind or 'absolute'})")
    else:
        lines.append("- **Rank (secondary):** _unset_")
    lines.append(f"- **Exit strategy:** {fields.get('exit_strategy')}")
    lines.append(f"- **Deadline:** {fields.get('deadline') or '_none_'}")
    lines.append("")
    lines.append("## Loop budget")
    lines.append("")
    lines.append(f"- **Max total pushes:** {fields.get('max_total_pushes')}")
    lines.append(f"- **Stuck threshold:** {fields.get('stuck_threshold')}")
    lines.append("")
    lines.append("## Status")
    lines.append("")
    lines.append(f"- **Status:** {fields.get('status')}")
    if row.get("closed_at"):
        lines.append(f"- **Closed at:** {_iso(row.get('closed_at'))}")
    if row.get("closed_reason"):
        lines.append(f"- **Closed reason:** {row.get('closed_reason')}")
    lines.append("")
    return "\n".join(lines)


def _write_goal_md(slug: str, row: dict) -> Path:
    path = _goal_md_path(slug)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_goal_md(slug, row), encoding="utf-8")
    return path


def parse_goal_md(text: str) -> dict:
    """Parse goal.md front-matter back into a field dict (round-trip helper).

    Minimal YAML: a leading ``---`` fenced block of ``key: value`` scalars.
    Used by tests + tooling to confirm goal.md reconstructs the row fields.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("goal.md missing leading '---' front-matter fence")
    out: dict = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" not in line:
            continue
        key, _, raw = line.partition(":")
        key = key.strip()
        raw = raw.strip()
        if raw == "null" or raw == "":
            out[key] = None
        elif raw in ("true", "false"):
            out[key] = raw == "true"
        else:
            try:
                out[key] = int(raw)
            except ValueError:
                try:
                    out[key] = float(raw)
                except ValueError:
                    out[key] = raw
    return out


# ---------------------------------------------------------------------------
# goal_remaining_delta
# ---------------------------------------------------------------------------


def _best_lb_score(_db, competition_id: str) -> float | None:
    """Best (max) scored public LB across this competition's submissions, or None.

    A higher-is-better metric is assumed (ADR-0020 §1 leaves metric direction
    to the caller; M14's primary getting-started surface is accuracy/F1). NULL
    when no submission has a recorded ``public_lb_score``.
    """
    conn = _db.get_conn()
    try:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT max(public_lb_score) AS best
                  FROM submissions
                 WHERE competition_id = %s::uuid
                   AND public_lb_score IS NOT NULL
                """,
                (competition_id,),
            )
            row = cur.fetchone()
    finally:
        conn.close()
    if not row or row["best"] is None:
        return None
    return float(row["best"])


def goal_remaining_delta(_db, competition_id: str, row: dict) -> float | None:
    """target_lb_score - best_current_lb (higher-is-better); None if unknowable.

    Positive ⇒ still below target. None when no target_lb_score is set or no
    scored submission exists yet. Never raises — DB failure ⇒ None.
    """
    target = row.get("target_lb_score")
    if target is None:
        return None
    try:
        best = _best_lb_score(_db, competition_id)
    except Exception:
        return None
    if best is None:
        return None
    return round(float(target) - best, 6)


