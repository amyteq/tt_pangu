    (skill / "SKILL.md").write_text(body.replace(original, replacement, 1), encoding="utf-8")
    monkeypatch.setattr(gen, "CLAUDE_SKILLS", tmp_path)
    with pytest.raises(SystemExit):
        gen.skill_front_matter("kg-run")


