@pytest.mark.parametrize(
    "text,allowed",
    [
        ("read `.vscode/.env.harry` or `.vscode/.env.may` to authenticate", True),
        ("read the per-account `.vscode/.env.*` files", False),
        ("read the per-account `.vscode/.env*` files", False),
        ("read `.vscode/.env.production` for the deploy key", False),
        ("read `.vscode/.env.?arry`", False),
        ("no credential files are named here at all", True),
    ],
)
def test_the_credential_allowlist_rule_separates_these_cases(text: str, allowed: bool):
    """The rule that guards the allowlist, exercised directly.

    `.vscode/.env.*` and `.vscode/.env*` are the same overreach spelled two ways;
    a substring ban catches whichever one it was written for and waves the other
    through, which is how the wildcard reached `main` in the first place.
    """
    named = set(CREDENTIAL_FILE_TOKEN.findall(text))
    assert named.issubset(ALLOWED_CREDENTIAL_FILES) is allowed


@pytest.mark.parametrize(
    "sentence,allowed",
    [
        ("`.env.production` and `.env.test` remain protected", True),
        ("never read `.env.production`", True),
        ("do not read `.env.production`", True),
        ("read `.env.production` to pick up the DSN", False),
        ("`.env.test` holds the staging credentials you need", False),
    ],
)
def test_the_protected_file_rule_separates_these_cases(sentence: str, allowed: bool):
    """The prohibition heuristic, exercised directly — including its false-positive risk.

    A skill correctly saying "never read `.env.production`" must pass; a skill
    offering it as a source must not. The heuristic reads sentences, not meaning,
    so these cases are the specification of what it actually promises.
    """
    forbidden = any(word in sentence.lower() for word in PROHIBITION_WORDS)
    assert forbidden is allowed


# Docs that `AGENTS.md` -> *Read first* sends Codex to. Banning a retired rule from
# AGENTS.md means little if AGENTS.md then points at a file that still states it:
# the agent reads the stale rule with the project doc's authority behind it.
REQUIRED_READING = [
    "PROJECT_STATE.md",
    "docs/engineering-practice.md",
]
# Matched case-insensitively: "Partly superseded" is the same commitment.
SUPERSESSION_MARKER = "superseded"


@pytest.mark.parametrize("doc", REQUIRED_READING)
def test_required_reading_is_listed_in_agents_md(doc: str, agents_md: str):
    """Keep this list honest: if AGENTS.md stops naming a doc, stop checking it."""
    assert doc in agents_md, (
        f"{doc} is in REQUIRED_READING but AGENTS.md no longer sends anyone to it — "
        "drop it here, or restore the pointer."
    )


@pytest.mark.parametrize("doc", REQUIRED_READING)
def test_required_reading_does_not_restate_retired_rules_unmarked(doc: str):
    """A doc Codex is told to read may hold an old rule only under a supersession note.

    Section-scoped: the note has to be in the same `## ` section as the stale rule,
    so a single marker at the top of a long file cannot vouch for everything below it.
    """
    text = (REPO_ROOT / doc).read_text(encoding="utf-8")
    sections = re.split(r"^(?=## )", text, flags=re.M)
    for rule in RETIRED_RULES + STALE_DIRECTION_PHRASES:
        for section in sections:
            if rule not in section:
                continue
            heading = section.splitlines()[0].strip()
            assert SUPERSESSION_MARKER.lower() in section.lower(), (
                f"{doc} section {heading!r} states the retired rule {rule!r} with no "
                f"{SUPERSESSION_MARKER!r} note, and AGENTS.md tells Codex to read this file. "
                "Add the note (naming what is current), or remove the rule."
            )


