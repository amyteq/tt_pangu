"""Instruction parity between the two harnesses (issue #189).

Claude Code loads `CLAUDE.md` + `.claude/`; Codex loads `AGENTS.md` + `.agents/`.
Phase 1 runs the same competition workflow from both, so the two instruction sets
must not drift. `AGENTS.md` and `.agents/` are generated by `scripts/gen_agents.py`;
these tests are the CI guard that says so.
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
CLAUDE_MD = REPO_ROOT / "CLAUDE.md"
AGENTS_MD = REPO_ROOT / "AGENTS.md"
GENERATOR = REPO_ROOT / "scripts" / "gen_agents.py"
CLAUDE_SKILLS = REPO_ROOT / ".claude" / "skills"
AGENTS_SKILLS = REPO_ROOT / ".agents" / "skills"

# Rules that must reach BOTH harnesses verbatim. One phrase per autonomy-relevant
# rule in CLAUDE.md — the rows of the issue #189 contradiction table, from the side
# that is current.
SHARED_RULES = [
    "Two agents: Claude Code harness vs KCA product",
    "autonomy.screen",
    "Read-for-use, not read-to-share",
    ".agent/kca/audit.jsonl",
    ".agent/audit/tool-events.jsonl",
    "Non-destructive GitHub writes are auto-allowed during dev phase",
    "Permanent-deletion remote writes require explicit human approval",
    "decision:confirmed",
    "untrusted data",
]

# Rules retired by the rewritten CLAUDE.md / ADR-0021. If one of these reappears in
# AGENTS.md, the old pre-#189 text has been restored and the harnesses contradict
# each other again.
RETIRED_RULES = [
    "Claude Agent SDK is the intended core production worker",
    "Do not push branches or create PRs without explicit human approval",
    "Return a plan and wait for human approval before editing files",
    "Never read, print, or commit secrets",
    "Do not submit to Kaggle or push remote kernels without explicit human approval",
]

# Retired *paths*. These are not caught by SHARED_RULES — asserting the current path
# appears somewhere says nothing about an obsolete one appearing elsewhere, and the
# Codex appendix is hand-written, so it can name a path CLAUDE.md never mentions.
# `.agent/audit.jsonl` was namespaced to `.agent/kca/audit.jsonl`; evidence written
# to the old path is evidence the eval sentinel never reads.
RETIRED_PATHS = [
    ".agent/audit.jsonl",
]

# The dev-phase secret policy is an allowlist of exact files. Any `.vscode/.env…`
# token a skill names must be one of them — that is what rules out `.vscode/.env.*`
# and `.vscode/.env*` alike, where a substring ban would only catch the spelling it
# was written for.
CREDENTIAL_FILE_TOKEN = re.compile(r"\.vscode/\.env[A-Za-z0-9_.*?\[\]-]*")
ALLOWED_CREDENTIAL_FILES = {
    ".vscode/.env.harry",
    ".vscode/.env.may",
}

# Files the policy withholds outright. A skill may name them, but only to forbid
# reading them.
PROTECTED_ENV_FILES = [
    ".env.production",
    ".env.test",
]
PROHIBITION_WORDS = ("never", "not ", "n't", "protected", "forbid", "exclude", "remain", "withheld")

# Phrases naming the pre-#188/#200 direction. Not banned outright — older docs may
# record what was once decided — but not without a supersession note, because a
# harness reading them cannot tell history from instruction.
STALE_DIRECTION_PHRASES = [
    "Claude Agent SDK for the production coding worker",
    "Claude Agent SDK worker",
    "PR merges (create is allowed, merge requires approval)",
    "Any remote write operation",
]

# Skills are symlinked into `.agents/`, so a stale rule in a skill body reaches Codex
# with the same authority as AGENTS.md — and a triggered skill is read *after* the
# project doc. Each entry is a phrase that contradicts a current shared rule, kept
# with the rule it contradicts so a future reader can tell why it is banned.
SKILL_CONTRADICTIONS = {
    "Never print or read Kaggle credentials": "dev-phase secret policy is read-for-use, not read-to-share",
    "merge is human-only": "dev-phase policy auto-allows `gh pr merge`; say 'from this skill' if scoping",
}


@pytest.fixture(scope="module")
def agents_md() -> str:
    return AGENTS_MD.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def claude_md() -> str:
    return CLAUDE_MD.read_text(encoding="utf-8")


def test_generated_files_are_current():
    """`AGENTS.md` + `.agents/` match what the generator would write right now."""
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "--check"],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    assert result.returncode == 0, (
        "AGENTS.md / .agents/ are out of date — run `python scripts/gen_agents.py` "
        f"and commit the result.\n\n{result.stdout}\n{result.stderr}"
    )


@pytest.mark.parametrize("rule", SHARED_RULES)
def test_shared_rule_reaches_both_harnesses(rule: str, claude_md: str, agents_md: str):
    assert rule in claude_md, f"{rule!r} is no longer in CLAUDE.md — update SHARED_RULES if that was deliberate"
    assert rule in agents_md, f"{rule!r} is missing from AGENTS.md — the harnesses have drifted"


@pytest.mark.parametrize("rule", RETIRED_RULES)
def test_retired_rule_is_gone(rule: str, agents_md: str):
    assert rule not in agents_md, f"AGENTS.md still carries the retired rule {rule!r} (issue #189 contradiction table)"


@pytest.mark.parametrize("path", RETIRED_PATHS)
def test_retired_path_is_not_advertised(path: str, agents_md: str):
    """AGENTS.md must not send an agent's evidence to a path nothing reads."""
    assert path not in agents_md, (
        f"AGENTS.md names the retired path {path!r}. Evidence written there is lost — "
        "use the current path (see the Two agents section)."
    )


@pytest.mark.parametrize("phrase,rule", sorted(SKILL_CONTRADICTIONS.items()))
def test_mirrored_skill_bodies_do_not_contradict_the_shared_rules(phrase: str, rule: str):
    """A mirrored skill carries the same authority as AGENTS.md — and is read later.

    Byte-identical mirroring is not enough: it faithfully republishes a stale rule.
    """
    for entry in sorted(AGENTS_SKILLS.iterdir()):
        body = (entry / "SKILL.md").read_text(encoding="utf-8")
        assert phrase not in body, (
            f"mirrored skill {entry.name!r} says {phrase!r}, which contradicts the shared rules "
            f"({rule}). Fix the skill under .claude/skills/ — the mirror is a symlink to it."
        )


def test_agents_md_fits_in_codex_project_doc_budget():
    """Codex truncates the project doc at `project_doc_max_bytes` (32 KiB default).

    Truncation is silent from the prompt's side — the rules that sort last would just
    stop reaching Codex. Keep CLAUDE.md lean instead of raising the limit.
    """
    size = AGENTS_MD.stat().st_size
    assert size < 32 * 1024, (
        f"AGENTS.md is {size} bytes; Codex truncates the project doc at 32 KiB, "
        "so the trailing rules would silently stop loading. Slim CLAUDE.md (issue #188)."
    )


def test_agents_md_names_the_harness_for_harness_specific_rules(agents_md: str):
    """A harness-specific rule must be readable by the other harness, not silently wrong."""
    assert "the harness you are" in agents_md
    assert "Codex" in agents_md


def test_skill_mirror_is_symlinks_to_the_same_bodies():
    """Every mirrored skill is a symlink into `.claude/skills/`, not a second copy."""
    assert AGENTS_SKILLS.is_dir(), ".agents/skills/ is missing — run `python scripts/gen_agents.py`"
    mirrored = sorted(AGENTS_SKILLS.iterdir())
    assert mirrored, ".agents/skills/ is empty"
    for entry in mirrored:
        assert entry.is_symlink(), f"{entry} is a copy, not a symlink — two copies is the drift we are preventing"
        resolved = entry.resolve()
        assert resolved.parent == CLAUDE_SKILLS.resolve(), f"{entry} points outside .claude/skills/"
        assert (resolved / "SKILL.md").is_file(), f"{entry} does not resolve to a SKILL.md"


def test_every_claude_skill_is_mirrored_or_documented():
    """No skill silently misses Codex: it is mirrored, or listed as excluded in the README."""
    readme = (REPO_ROOT / ".agents" / "README.md").read_text(encoding="utf-8")
    for skill_dir in sorted(CLAUDE_SKILLS.iterdir()):
        if not (skill_dir / "SKILL.md").is_file():
            continue
        name = skill_dir.name
        mirrored = (AGENTS_SKILLS / name).is_symlink()
        documented = f"| `{name}` |" in readme
        assert mirrored or documented, f"skill {name!r} is neither mirrored into .agents/ nor documented as excluded"


def test_mirrored_skills_name_only_allowlisted_credential_files():
    """A skill may restate the dev-phase secret policy; it may not enlarge it.

    Matched by *token*, not by substring: `.vscode/.env*` and `.vscode/.env.*` are
    different spellings of the same overreach, and a substring check for one misses
    the other. A mirrored skill is read *after* the project doc, so the wider
    wording is the one in front of the agent.
    """
    for entry in sorted(AGENTS_SKILLS.iterdir()):
        body = (entry / "SKILL.md").read_text(encoding="utf-8")
        for token in set(CREDENTIAL_FILE_TOKEN.findall(body)):
            assert token in ALLOWED_CREDENTIAL_FILES, (
                f"mirrored skill {entry.name!r} names {token!r}. The dev-phase secret policy "
                f"allows exactly {sorted(ALLOWED_CREDENTIAL_FILES)} — name those, not a pattern."
            )


@pytest.mark.parametrize("path", PROTECTED_ENV_FILES)
def test_mirrored_skills_mention_protected_env_files_only_to_forbid_them(path: str):
    """`.env.production` / `.env.test` may be named, but only in a prohibition.

    Banning the string outright would fail a skill that correctly says "never read
    `.env.production`", so the sentence around each mention has to carry the refusal.
    That is a heuristic: it reads sentences, not meaning. It catches the realistic
    slip — a permission sentence listing a protected file — and is deliberately
    loose about how the prohibition is phrased.
    """
    for entry in sorted(AGENTS_SKILLS.iterdir()):
        body = (entry / "SKILL.md").read_text(encoding="utf-8")
        for sentence in re.split(r"(?<=[.;:!?])\s+|\n", body):
            if path not in sentence:
                continue
            assert any(word in sentence.lower() for word in PROHIBITION_WORDS), (
                f"mirrored skill {entry.name!r} names the protected file {path!r} in a sentence "
                f"that does not forbid reading it:\n    {sentence.strip()[:160]!r}"
            )


