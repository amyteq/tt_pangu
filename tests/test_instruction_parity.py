CODE_FENCE = re.compile(r"^ {0,3}(?P<mark>`{3,}|~{3,})(?P<info>.*)$")
LIST_MARKER = re.compile(r"(?:[-*+>]|\d+[.)])\s")
INLINE_CODE = re.compile(r"`+[^`]*(?:`+|$)")
WORD = re.compile(r"\w")
INDENTS = ("    ", "\t")
# A list item's marker, which sets the column its own content — and therefore its own
# block structure — starts at. CommonMark measures a block start from the enclosing
# container's content column and not from column 0, so `<!--` four spaces into a `- `
# item is a real start condition; #217 shape 2 was exactly that, read here as prose.
LIST_ITEM_START = re.compile(r"^(?P<indent> {0,3})(?P<marker>[-*+]|\d{1,9}[.)])(?P<space> {1,4}|\t)")
# The two leaf blocks that look like prose to a line scanner and are not paragraph
# content. They matter only because start condition 7 may not interrupt a *paragraph*:
# a line after a heading or a thematic break interrupts nothing.
ATX_HEADING = re.compile(r"^ {0,3}#{1,6}(?:[ \t]|$)")
THEMATIC_BREAK = re.compile(r"^ {0,3}(?P<char>[-*_])(?:[ \t]*(?P=char)){2,}[ \t]*$")


def _fence_delimiter(line: str) -> re.Match[str] | None:
    """The line read as a CommonMark fence delimiter, or `None` if it is ordinary text.

    `CODE_FENCE` on its own is too permissive in one way that matters. CommonMark forbids
    a backtick anywhere in the info string of a *backtick* fence — that rule exists exactly
    so a same-line span stays inline code — and a line holding one whole sentence between
    two triple-backtick runs is such a span: CommonMark renders it `<p><code>…</code></p>`.
    Read as an opener instead, the line is dropped as a delimiter and the sentence on it is
    never scanned at all, which is worse than mis-tagging it: at the end of a file the
    sentence silently vanishes from the pin, and mid-file the unterminated fence retags
    every later mention as code. A tilde fence carries no such restriction, so `~~~x~~~`
    really is an opener and stays one.
    """
    opener = CODE_FENCE.match(line)
    if opener and opener["mark"].startswith("`") and "`" in opener["info"]:
        return None
    return opener


# CommonMark § "HTML blocks", by start condition, in the spec's order — which is what
# keeps `<![CDATA[` out of condition 4's `<!` + letter. Each row is (start, end, tag):
# `end` closes the block on the line that matches it (conditions 1-5, where a blank line
# does *not* end the block), or is `None` for the two conditions a blank line closes
# (6 and 7). Condition 1 is split three ways because its four tag names do not render
# alike: `<pre>` is preformatted, `<script>` / `<style>` are not shown at all, and
# `<textarea>` is neither.
HTML_NAME = r"[A-Za-z][A-Za-z0-9-]*"
HTML_ATTRIBUTE = r"""\s+[A-Za-z_:][A-Za-z0-9_.:-]*(?:\s*=\s*(?:[^\s"'=<>`]+|'[^']*'|"[^"]*"))?"""
HTML_RAW_CLOSE = re.compile(r"</(?:pre|script|style|textarea)>", re.I)
# Condition 6's list of block-level names, as the spec gives it (both `search` and
# `source`, which different spec versions list). A name outside it reaches condition 7.
HTML_BLOCK_NAMES = (
    "address|article|aside|base|basefont|blockquote|body|caption|center|col|colgroup|dd|"
    "details|dialog|dir|div|dl|dt|fieldset|figcaption|figure|footer|form|frame|frameset|"
    "h1|h2|h3|h4|h5|h6|head|header|hr|html|iframe|legend|li|link|main|menu|menuitem|nav|"
    "noframes|ol|optgroup|option|p|param|search|section|source|summary|table|tbody|td|"
    "tfoot|th|thead|title|tr|track|ul"
)
HTML_BLOCKS: tuple[tuple[re.Pattern[str], re.Pattern[str] | None, str], ...] = (
    (re.compile(r"^ {0,3}<pre(?=[\s>]|$)", re.I), HTML_RAW_CLOSE, CODE_PIN),
    (re.compile(r"^ {0,3}<(?:script|style)(?=[\s>]|$)", re.I), HTML_RAW_CLOSE, HIDDEN_PIN),
    (re.compile(r"^ {0,3}<textarea(?=[\s>]|$)", re.I), HTML_RAW_CLOSE, HTML_PIN),
    (re.compile(r"^ {0,3}<!--"), re.compile(r"-->"), HIDDEN_PIN),
    (re.compile(r"^ {0,3}<\?"), re.compile(r"\?>"), HIDDEN_PIN),
    (re.compile(r"^ {0,3}<!\[CDATA\["), re.compile(r"\]\]>"), HIDDEN_PIN),
    (re.compile(r"^ {0,3}<![A-Za-z]"), re.compile(r">"), HIDDEN_PIN),
    (re.compile(rf"^ {{0,3}}</?(?:{HTML_BLOCK_NAMES})(?=[\s>]|/>|$)", re.I), None, HTML_PIN),
)
# Condition 7: one complete open or closing tag, alone on its line, under any name at all
# — which is the shape that would otherwise let `<wrapper>` do what `<div>` cannot. The
# four names of condition 1 are excluded by the spec, and this is the one condition that
# may not interrupt a paragraph, so `_html_block` is told whether a block can start here.
HTML_TAG_ALONE = re.compile(
    rf"^ {{0,3}}(?:<(?!(?:pre|script|style|textarea)[\s/>]){HTML_NAME}(?:{HTML_ATTRIBUTE})*\s*/?>"
    rf"|</{HTML_NAME}\s*>)\s*$",
    re.I,
)
# Markup and nothing else is dropped, exactly as a fence delimiter is: `<div>` around a
# rule is rendering, and swapping it for `<section>` is not drift. A delimiter sharing its
# line with text — `<!-- the rule -->` — carries the text and stays.
HTML_MARKUP_ONLY = re.compile(
    rf"""^\s*(?:</?{HTML_NAME}(?:{HTML_ATTRIBUTE})*\s*/?>|<!--|-->|<!\[CDATA\[|\]\]>|<\?|\?>)\s*$""",
    re.I,
)


def _html_block(line: str, may_start: bool) -> tuple[re.Pattern[str] | None, str] | None:
    """`(end, tag)` if `line` opens a raw HTML block, else `None`.

    `may_start` is false inside a paragraph, where only condition 7 is forbidden — the
    other seven may interrupt one, and a `<!--` opened mid-paragraph really does swallow
    what follows.
    """
    for start, end, tag in HTML_BLOCKS:
        if start.match(line):
            return end, tag
    return (None, HTML_PIN) if may_start and HTML_TAG_ALONE.match(line) else None


def _container_indent(line: str, current: int) -> int:
    """The content column of the innermost list item still open after `line`.

    One level, which is what the counterexample needs and all the scanned surfaces use. A
    list item opens one at its marker; a blank line does not close a list; anything that
    falls back to the left of the content column does. Nested items are read as the
    innermost marker's column, so a deeper start than one level is measured from too far
    right and under-tags — the direction this whole module errs in.
    """
    item = LIST_ITEM_START.match(line)
    if item and not THEMATIC_BREAK.match(line):
        # `- - -` matches a bullet and its content, and CommonMark resolves it the other
        # way: a thematic break wins over a list item, and opens no container at all.
        return len(item["indent"]) + len(item["marker"]) + len(item["space"])
    if not line.strip():
        return current
    return current if current and line.startswith(" " * current) else 0


def _undent(line: str, container: int) -> str:
    """`line` with the enclosing list item's content indent removed, for block-start tests.

    Only the tests: the tag, the pinned text and everything downstream keep reading the
    real line. This exists so `^ {0,3}` is measured from where the container's content
    begins, which is what CommonMark measures it from.
    """
    return line[container:] if container and not line[:container].strip() else line


def _line_blocks(lines: list[str]) -> list[str | None]:
    """Per line: the tag of the block it sits in, or `None` for a delimiter, which is in none.

    Fenced blocks are tracked exactly — a delimiter is what `_fence_delimiter` accepts, a
    closing fence is the same character, at least as long as its opener, and carries no
    info string. The ``` and ~~~ lines themselves are dropped so that the fence character
    and its info string stay out of the pin: swapping ```` ```sh ```` for ```` ```bash ````
    is rendering, like emphasis.

    An indented block is recognised only in the shape CommonMark leaves no room to argue
    about: a blank line, then four spaces, under a line that starts at column 0 and is not
    a list marker. Four spaces under a bullet is that bullet's *content*, and calling prose
    code would reopen the very hole this split closes, so that shape stays prose —
    under-tagging on purpose.

    A raw HTML block runs from its start condition to the end that condition names, and
    nothing inside it is markdown — a fence opener inside a comment is four characters of
    commented-out text. The precedence runs both ways, and in the spec's order: a fenced
    block is checked first, so `<!--` inside a fence is example text too.

    Two things decide where a raw HTML block may start, and #217 is why both are here.
    `paragraph` is what condition 7 may not interrupt — not a preceding blank line, which
    is stricter and missed a start on the line after a one-line comment closed. `container`
    is the enclosing list item's content column, which is where CommonMark measures a start
    condition from, so `<!--` four spaces into a `- ` item opens the block it really opens.

    One gap remains here, stated rather than discovered:
    `test_container_tracking_reaches_one_level_and_these_are_outside_it` pins it. Container
    tracking follows the innermost list marker within `^ {0,3}`, so a marker indented four
    or more is measured from too far right and a start below it is read as prose. Every list
    on every scanned surface is inside that bound. A third #217 shape is not this function's
    to fix at all — inline HTML is never inspected, so an unclosed tag on a neighbouring line
    hides a rule whose own bytes are untouched, and that is recorded as accepted residual
    risk by `test_inline_html_hiding_a_rule_is_accepted_residual_risk`.
    """
    tags: list[str | None] = []
    fence = ""
    html: tuple[re.Pattern[str] | None, str] | None = None
    indented = False
    preceding = ""  # the last prose line, which decides whether an indent opens a block
    blank = True
    paragraph = False  # a paragraph is open here, which is the only thing condition 7 may not interrupt
    container = 0  # the enclosing list item's content column, which block starts are measured from
    for line in lines:
        probe = _undent(line, container)
        container = _container_indent(line, container)
        if html is not None:
            end, tag = html
            if end is None and not line.strip():
                # Conditions 6 and 7 end at a blank line, which is outside the block.
                html, blank, paragraph = None, True, False
                tags.append(PROSE_PIN)
                continue
            tags.append(None if HTML_MARKUP_ONLY.match(line) else tag)
            if end is not None and end.search(line):
                html = None
            paragraph = False
            continue
        opener = _fence_delimiter(probe)
        closes = (
            opener
            and fence
            and opener["mark"][0] == fence[0]
            and len(opener["mark"]) >= len(fence)
            and not opener["info"].strip()
        )
        if fence:
            tags.append(None if closes else CODE_PIN)
            fence = "" if closes else fence
            paragraph = False
            continue
        if opener:
            fence, indented, blank, paragraph = opener["mark"], False, False, False
            tags.append(None)
            continue
        opens_html = _html_block(probe, not paragraph)
        if opens_html is not None:
            end, tag = opens_html
            # The start line is checked for its own end condition: `<!-- a rule -->` is a
            # one-line block, and so is `<!DOCTYPE html>`.
            html = None if end is not None and end.search(line) else opens_html
            indented, blank, paragraph = False, False, False
            tags.append(None if HTML_MARKUP_ONLY.match(line) else tag)
            continue
        if not line.strip():
            # A blank line inside an indented block does not end it.
            tags.append(CODE_PIN if indented else PROSE_PIN)
            blank, paragraph = True, False
            continue
        if indented and line.startswith(INDENTS):
            tags.append(CODE_PIN)
            blank, paragraph = False, False
            continue
        indented = bool(
            blank
            and line.startswith(INDENTS)
            and preceding
            and preceding[:1] not in " \t"
            and not LIST_MARKER.match(preceding)
        )
        tags.append(CODE_PIN if indented else PROSE_PIN)
        # Only paragraph content opens a paragraph. Indented code is not prose at all, and
        # a heading or a thematic break is a leaf block the next line does not interrupt.
        paragraph = not indented and not ATX_HEADING.match(line) and not THEMATIC_BREAK.match(line)
        preceding, blank = line, False
    return tags


def _blocks(text: str) -> list[tuple[str, str]]:
    """`(tag, chunk)` runs of the document, one run per block the pin tags differently."""
    lines = text.splitlines()
    runs: list[tuple[str, list[str]]] = []
    for line, tag in zip(lines, _line_blocks(lines)):
        if tag is None:
            continue
        if runs and runs[-1][0] == tag:
            runs[-1][1].append(line)
        else:
            runs.append((tag, [line]))
    return [(tag, "\n".join(chunk)) for tag, chunk in runs if "\n".join(chunk).strip()]


def _is_code_span(sentence: str) -> bool:
    """True when the sentence is code the whole way through — `like this`, and nothing else.

    A sentence that *contains* code spans is prose, and `_pin_text` drops the ticks so that
    back-ticking a filename is not drift. A sentence that *is* one is not prose at all.
    `INLINE_CODE` lets an unterminated span run to the end of the string because
    `MENTION_BREAK` takes the closing tick with it when it ends a sentence on ``.` ``.
    """
    return "`" in sentence and not WORD.search(INLINE_CODE.sub(" ", sentence))


def _plain(sentence: str) -> str:
    """The sentence as it renders: emphasis and code ticks gone, whitespace collapsed."""
    return " ".join(sentence.replace("*", "").replace("`", "").split())


def _pin_text(sentence: str, *, tag: str = PROSE_PIN) -> str:
    """The pinned form: what `_plain` leaves, tagged with the block it was found in."""
    return tag + _plain(sentence)


def _mentions(text: str, trigger: Callable[[str], bool]) -> tuple[str, ...]:
    """Every pinnable sentence of `text` that the trigger matches, in document order.

    `MENTION_BREAK` is a deterministic split, not a linguistically correct one, and it
    does not need to be: the pin makes no claim about what a sentence means, only that the
    same document splits the same way twice. It runs inside a block rather than across the
    document, so a rule and the example under it can never merge into one pin.

    The trigger reads `_plain(part)` — what the sentence renders as — and not the source
    line. Triggering on the source made the scan depend on where the line breaks fell: a
    trigger spelled with a space, `requires human approval` or `screened submit`, missed
    its own rule the moment a contributor hard-wrapped the paragraph between those two
    words, and the sentence left the scan rather than drifting. Emphasis did the same to
    `force-**push**`. Normalising first is what makes "a hard-wrap/soft-wrap change is not
    drift" true of the whole pin rather than only of its text.

    Inline code promotes prose to `[code] ` and nothing else: inside a raw HTML block a
    backtick is a backtick, markdown having stopped running there, so the block's own tag
    stands.
    """
    return tuple(
        _pin_text(part, tag=CODE_PIN if tag == PROSE_PIN and _is_code_span(part) else tag)
        for tag, chunk in _blocks(text)
        for part in MENTION_BREAK.split(chunk)
        if part and part.strip() and trigger(_plain(part))
    )


def _skill_surfaces() -> list[str]:
    return [f".agents/skills/{entry.name}/SKILL.md" for entry in sorted(AGENTS_SKILLS.iterdir())]


def _scans(topic: _MentionTopic) -> list[str]:
    """Every file a topic reads: the documents it lists, plus the mirrored skills.

    One definition, used both by the scan and by the tests that assert a case is about a
    file the scan actually opens — those doctor one surface's text in memory, so without
    this they would go on passing if the file were dropped from `POLICY_SURFACES`.
    """
    return [*topic.docs, *(_skill_surfaces() if topic.skills else [])]


def _collect_mentions(name: str) -> dict[str, tuple[str, ...]]:
    topic = MENTION_TOPICS[name]
    found: dict[str, tuple[str, ...]] = {}
    for rel in _scans(topic):
        hits = _mentions((REPO_ROOT / rel).read_text(encoding="utf-8"), topic.trigger)
        if hits:
            found[rel] = hits
    return found


def _pin_diff(pinned: dict[str, tuple[str, ...]], found: dict[str, tuple[str, ...]]) -> list[str]:
    """Every way the scanned surfaces differ from what was reviewed."""
    problems = []
    for rel in sorted(set(pinned) | set(found)):
        was, now = pinned.get(rel, ()), found.get(rel, ())
        if was == now:
            continue
        if set(was) == set(now):
            problems.append(f"{rel}: the same mentions in a different order")
            continue
        problems.extend(f"{rel}: not reviewed: {text}" for text in now if text not in was)
        problems.extend(f"{rel}: reviewed text is gone or altered: {text}" for text in was if text not in now)
    return problems


def _pin_literal(name: str, found: dict[str, tuple[str, ...]]) -> str:
    lines = []
    for rel, sentences in found.items():
        lines.append(f'    ("{name}", "{rel}"): (')
        lines.extend(f"        {sentence!r}," for sentence in sentences)
        lines.append("    ),")
    return "\n".join(lines)


